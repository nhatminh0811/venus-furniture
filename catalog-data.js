const categoryPricing = {
  Sofas: [28000000, 3500000],
  Thảm: [3200000, 850000],
  Giường: [22000000, 2800000],
  Bàn: [8500000, 2200000],
  Ghế: [4800000, 1350000],
  'Tủ kệ': [10500000, 2600000],
  'Đèn': [3200000, 1250000],
  Decor: [850000, 420000],
};

window.VENUS_CATALOG.forEach(({ category, files }) => {
  const profile = productProfiles[category];
  const [basePrice, priceStep] = categoryPricing[category];
  files.forEach((product, index) => {
    const filename = typeof product === 'string' ? product : product.filename;
    const name = typeof product === 'string' ? filename.replace(/\.[^.]+$/, '').trim() : product.name;
    const categoryProfile = category === 'Decor' && name.startsWith('Chăn')
      ? { ...profile, specs: profile.variants }
      : profile;
    const specs = category === 'Decor'
      ? categoryProfile.specs
      : index % 2 === 0 ? categoryProfile.specs : categoryProfile.variants;
    const descriptions = profile.descriptions;
    const materials = specs.find(([label]) => ['Chất liệu', 'Chất liệu bọc', 'Mặt bàn', 'Hoàn thiện'].includes(label));
    const description = `${name} ${descriptions[index % descriptions.length]}.`;
    const details = specs.map(([label, value]) => [label, value]);
    const productDetails = {
      description,
      specs: details,
      material: materials?.[1] || specs[0][1],
      price: basePrice + priceStep * index,
    };
    if (typeof product === 'string') {
      files[index] = { filename, name, details: productDetails };
    } else {
      product.details = productDetails;
    }
  });
});
